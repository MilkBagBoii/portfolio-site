const state = {
  activeEngine: "All"
};

const bySelector = (selector) => document.querySelector(selector);
const allBySelector = (selector) => Array.from(document.querySelectorAll(selector));

function setProfileContent() {
  document.title = portfolio.siteTitle;
  allBySelector("[data-profile-name]").forEach((node) => {
    node.textContent = portfolio.name;
  });
  allBySelector("[data-itch-link]").forEach((node) => {
    node.href = portfolio.itchUrl;
  });

  const emailLink = bySelector("[data-email-link]");
  if (emailLink) {
    emailLink.href = `mailto:${portfolio.email}`;
  }

  const brandMark = bySelector(".brand-mark");
  if (brandMark) {
    brandMark.textContent = portfolio.initials;
  }
  bySelector("[data-profile-summary]").textContent = portfolio.summary;
  bySelector("[data-build-status]").textContent = portfolio.status;
  bySelector("[data-contact-heading]").textContent = "Let us build something playable.";

}

function renderEngines() {
  const grid = bySelector("[data-engine-grid]");
  grid.innerHTML = "";

  portfolio.engines.forEach((engine) => {
    const card = document.createElement("a");
    card.className = "engine-card";
    card.href = "#work";
    card.setAttribute("aria-label", `View ${engine.name} projects`);
    const token = engine.logo
      ? `<span class="engine-token has-logo" style="--engine-color:${engine.color}"><img src="${engine.logo}" alt="${engine.name} logo"></span>`
      : `<span class="engine-token" style="background:${engine.color}">${engine.initials}</span>`;

    card.innerHTML = `
      <div class="engine-meta">
        ${token}
      </div>
      <h3>${engine.name}</h3>
      <p>${engine.notes}</p>
    `;
    card.addEventListener("click", () => {
      state.activeEngine = engine.name;
      renderFilters();
      renderProjects();
    });
    grid.appendChild(card);
  });
}

function renderFilters() {
  const row = bySelector("[data-filter-row]");
  const engineNames = ["All", ...portfolio.engines.map((engine) => engine.name)];
  row.innerHTML = "";

  engineNames.forEach((engineName) => {
    const button = document.createElement("button");
    button.className = `filter-button${engineName === state.activeEngine ? " is-active" : ""}`;
    button.type = "button";
    button.textContent = engineName;
    button.setAttribute("aria-pressed", String(engineName === state.activeEngine));
    button.addEventListener("click", () => {
      state.activeEngine = engineName;
      renderFilters();
      renderProjects();
    });
    row.appendChild(button);
  });
}

function renderProjects() {
  const grid = bySelector("[data-project-grid]");
  const projects =
    state.activeEngine === "All"
      ? portfolio.projects
      : portfolio.projects.filter((project) => project.engine === state.activeEngine);

  grid.innerHTML = "";

  projects.forEach((project) => {
    const card = document.createElement("article");
    card.className = "project-card";
    card.style.setProperty("--art-a", project.colorA);
    card.style.setProperty("--art-b", project.colorB);

    const publicLink = project.publicUrl
      ? `<a class="text-link" href="${project.publicUrl}" target="_blank" rel="noreferrer">Play / view</a>`
      : `<span class="text-link secondary is-disabled" aria-label="Not currently playable">Not playable yet</span>`;
    const videoLink = project.videoUrl
      ? `<a class="text-link secondary" href="${project.videoUrl}" target="_blank" rel="noreferrer">Video</a>`
      : "";
    const sourceLink = project.sourceUrl
      ? `<a class="text-link secondary" href="${project.sourceUrl}" target="_blank" rel="noreferrer">Source</a>`
      : "";
    const art = project.image
      ? `<img src="${project.image}" alt="${project.title} artwork">`
      : `<span>${project.engine.slice(0, 2).toUpperCase()}</span>`;

    card.innerHTML = `
      <div class="project-art ${project.imageMode === "contain" ? "is-contain" : ""}">${art}</div>
      <div class="project-body">
        <div class="tag-row">
          <span class="tag">${project.engine}</span>
          <span class="tag">${project.type}</span>
          <span class="tag">${project.year}</span>
        </div>
        <h3>${project.title}</h3>
        <p>${project.description}</p>
        <div class="project-links">${publicLink}${videoLink}${sourceLink}</div>
      </div>
    `;
    grid.appendChild(card);
  });
}

function renderSkills() {
  const matrix = bySelector("[data-skill-matrix]");
  matrix.innerHTML = "";

  portfolio.skills.forEach((skill) => {
    const item = document.createElement("article");
    item.className = "skill-item";
    item.innerHTML = `
      <h3>${skill.title}</h3>
      <p>${skill.text}</p>
    `;
    matrix.appendChild(item);
  });
}

function renderGamesList() {
  const list = bySelector("[data-games-list]");
  const publicProjects = portfolio.projects.filter((project) => project.publicUrl);
  list.innerHTML = "";

  publicProjects.forEach((project) => {
    const row = document.createElement("article");
    const statusText = project.status.toLowerCase();
    const statusClass = statusText.includes("prototype")
      ? "prototype"
      : statusText.includes("development")
        ? "development"
        : project.type.toLowerCase().includes("jam")
          ? "jam"
          : "";

    row.className = "game-row";
    row.innerHTML = `
      <div>
        <h3>${project.title}</h3>
        <p>${project.description}</p>
      </div>
      <div class="game-detail">${project.engine}</div>
      <span class="status-pill ${statusClass}">${project.status}</span>
      <a class="button button-primary" href="${project.publicUrl}" target="_blank" rel="noreferrer">Play</a>
    `;
    list.appendChild(row);
  });

  if (!publicProjects.length) {
    const empty = document.createElement("p");
    empty.textContent = "Add publicUrl values in script.js and your released games will appear here.";
    list.appendChild(empty);
  }
}

function setupNavigation() {
  const toggle = bySelector(".nav-toggle");
  const links = bySelector(".nav-links");

  toggle.addEventListener("click", () => {
    const isOpen = document.body.classList.toggle("nav-open");
    toggle.setAttribute("aria-expanded", String(isOpen));
  });

  links.addEventListener("click", (event) => {
    if (event.target.matches("a")) {
      document.body.classList.remove("nav-open");
      toggle.setAttribute("aria-expanded", "false");
    }
  });
}

function setupHeaderShadow() {
  const header = bySelector("[data-nav]");
  const onScroll = () => {
    header.style.boxShadow = window.scrollY > 12 ? "0 10px 34px rgba(0, 0, 0, 0.36)" : "none";
  };

  onScroll();
  window.addEventListener("scroll", onScroll, { passive: true });
}

function getVideoEmbedUrl(url) {
  if (!url) {
    return "";
  }

  try {
    const parsed = new URL(url);
    const host = parsed.hostname.replace(/^www\./, "");

    if (host === "youtu.be") {
      return `https://www.youtube.com/embed/${parsed.pathname.slice(1)}`;
    }

    if (host === "youtube.com" || host === "m.youtube.com") {
      if (parsed.pathname === "/watch") {
        const id = parsed.searchParams.get("v");
        return id ? `https://www.youtube.com/embed/${id}` : "";
      }

      if (parsed.pathname.startsWith("/shorts/")) {
        return `https://www.youtube.com/embed/${parsed.pathname.split("/")[2]}`;
      }

      if (parsed.pathname.startsWith("/embed/")) {
        return url;
      }
    }

    if (host === "vimeo.com") {
      const id = parsed.pathname.split("/").filter(Boolean).pop();
      return id ? `https://player.vimeo.com/video/${id}` : "";
    }
  } catch {
    return "";
  }

  return "";
}

function renderReel() {
  const slot = bySelector("[data-reel-slot]");
  const reelUrl = portfolio.reelUrl.trim();
  const embedUrl = getVideoEmbedUrl(reelUrl);
  const directVideo = /\.(mp4|webm|ogg)$/i.test(reelUrl);
  const needsFileFallback = window.location.protocol === "file:" && embedUrl.includes("youtube.com");

  if (embedUrl && !needsFileFallback) {
    slot.innerHTML = `
      <iframe
        src="${embedUrl}"
        title="${portfolio.reelTitle}"
        loading="lazy"
        allow="accelerometer; autoplay; clipboard-write; encrypted-media; gyroscope; picture-in-picture; web-share"
        referrerpolicy="strict-origin-when-cross-origin"
        allowfullscreen>
      </iframe>
    `;
    return;
  }

  if (directVideo) {
    slot.innerHTML = `
      <video controls preload="metadata">
        <source src="${reelUrl}">
      </video>
    `;
    return;
  }

  const fallbackLink = reelUrl
    ? `<a class="button button-primary" href="${reelUrl}" target="_blank" rel="noreferrer">Open reel</a>`
    : "";

  slot.innerHTML = `
    <div class="reel-placeholder">
      <div class="play-mark" aria-hidden="true"></div>
      <div>
        <p class="reel-label">Gameplay reel</p>
        <h2>${portfolio.reelTitle}</h2>
        <p>${needsFileFallback ? "Open the reel on YouTube while previewing locally. The embed will play when the site is hosted." : "Gameplay clips, prototypes, and released projects."}</p>
        ${fallbackLink}
      </div>
    </div>
  `;
}

